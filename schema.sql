CREATE DATABASE IF NOT EXISTS srms CHARACTER SET utf8mb4;
USE srms;
CREATE TABLE IF NOT EXISTS admins(id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(50) UNIQUE, password VARCHAR(255));
CREATE TABLE IF NOT EXISTS students(id INT AUTO_INCREMENT PRIMARY KEY, reg_no VARCHAR(30) UNIQUE, name VARCHAR(100), class VARCHAR(30), password VARCHAR(255));
CREATE TABLE IF NOT EXISTS subjects(id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) UNIQUE);
CREATE TABLE IF NOT EXISTS results(id INT AUTO_INCREMENT PRIMARY KEY, student_id INT, subject_id INT, session VARCHAR(9), term TINYINT, ca TINYINT UNSIGNED, exam TINYINT UNSIGNED,
 UNIQUE(student_id,subject_id,session,term),
 FOREIGN KEY(student_id) REFERENCES students(id) ON DELETE CASCADE,
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE CASCADE);
